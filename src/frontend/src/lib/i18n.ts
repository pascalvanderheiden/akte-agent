export const catalogs: Record<Locale, Record<TranslationKey, string>> = { en, nl };

export function translate(locale: Locale, key: TranslationKey, params: TranslationParams = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name];
    if (value === undefined) throw new Error(`Missing translation parameter: ${key}.${name}`);
    return typeof value === "number" ? new Intl.NumberFormat(localeTag[locale]).format(value) : value;
  });
}
