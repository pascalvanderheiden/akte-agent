import type { Locale, UseCase } from "../types";

export const LOCALE_STORAGE_KEY = "kratos.locale";
export const localeTag: Record<Locale, string> = { en: "en-GB", nl: "nl-NL" };

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "nl";
}

export function resolveLocale(saved: unknown, languages: readonly string[]): Locale {
  if (isLocale(saved)) return saved;
  for (const language of languages) {
    const primary = language.toLowerCase().split("-")[0];
    if (isLocale(primary)) return primary;
  }
  return "en";
}

export function localizeUseCase(persona: UseCase, locale: Locale): UseCase {
  const translation = persona.localizations?.[locale];
  return {
    ...persona,
    displayName: translation?.displayName ?? persona.displayName,
    description: translation?.description ?? persona.description,
    sampleQuestions: translation?.sampleQuestions ?? persona.sampleQuestions,
  };
}

